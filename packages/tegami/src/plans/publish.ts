/** default max amount of concurrently running publish tasks & status checks */
const DEFAULT_CONCURRENCY = 5;

function assertConcurrency(concurrency: number): void {
  if (!Number.isSafeInteger(concurrency) || concurrency < 1) {
    throw new RangeError(`Task concurrency must be a positive integer, received ${concurrency}.`);
  }
}

export interface PublishPlan {
  options: PublishOptions;

  /** id -> entry */
  changelogs: Map<string, ChangelogEntry>;
  /** id -> package data. The package id will always exist in package graph, stale items will be pruned at init-time */
  packages: Map<string, PackagePublishPlan>;

  /** every publish task of the run */
  tasks: readonly PublishTask[];

  /** the packages of the plan that should publish, resolved by preflights */
  getPackagesToPublish(): WorkspacePackage[];

  /** generated by GitHub/GitLab plugin (internal) */
  $versionRequest?: {
    publishGroups: Map<string, "active" | "pending">;
  };
}

export interface PackagePublishPlan {
  changelogs: ChangelogEntry[];
  /** whether this package was version-bumped when the lock was written */
  updated: boolean;

  /** generated by Git plugin */
  git?: {
    /** the associated Git tag of package */
    tag?: string;
  };

  /** generated by npm plugin */
  npm?: {
    /** dist tag to use if published */
    distTag?: string;

    /** point latest tag to it if published */
    markLatest?: boolean;
  };

  /**
   * Publish result, derived from the package's publish tasks: `undefined` until they
   * settle, `skipped` for packages without a publish task.
   */
  readonly publishResult?: PackagePublishResult;

  /** preflight result, generated for all packages in publish plan after preflights */
  preflight?: PublishPreflight;
}

const packagePublishTasks = new WeakMap<PackagePublishPlan, PackagePublishTask>();

export async function initPublishPlan(
  context: TegamiContext,
  options: PublishOptions,
): Promise<PublishPlan | undefined> {
  let lock: PublishLock;
  try {
    lock = parsePublishLock(await fs.readFile(context.lockPath, "utf8"));
  } catch {
    return;
  }

  let data: unknown;
  const packages = new Map<string, PackagePublishPlan>();
  const changelogs = new Map<string, ChangelogEntry>();
  const plan: PublishPlan = {
    options,
    changelogs,
    packages,
    tasks: [],
    getPackagesToPublish() {
      const result: WorkspacePackage[] = [];

      for (const [id, packagePlan] of packages) {
        if (!packagePlan.preflight?.shouldPublish) continue;
        const pkg = context.graph.get(id);
        if (pkg) result.push(pkg);
      }

      return result;
    },
  };

  while ((data = lock.read("core:changelogs"))) {
    const validated = validateChangelogStore(data);
    if (!validated.success) continue;
    const entry = validated.data;
    const parsed = parseChangelogFile(entry.filename, entry.content);
    if (!parsed) continue;

    changelogs.set(parsed.id, parsed);
  }

  while ((data = lock.read("core:packages"))) {
    const validated = validatePackageStore(data);
    if (!validated.success) continue;
    const parsed = validated.data;
    if (!context.graph.get(parsed.id)) continue;

    const pkgChangelogs: ChangelogEntry[] = [];
    for (const id of parsed.changelogIds ?? []) {
      const entry = changelogs.get(id);
      if (entry) pkgChangelogs.push(entry);
    }
    packages.set(parsed.id, {
      changelogs: pkgChangelogs,
      updated: parsed.updated,
      get publishResult(): PackagePublishResult | undefined {
        if (!this.preflight) return;
        if (!this.preflight.shouldPublish) return { type: "skipped" };

        const state = packagePublishTasks.get(this)?.getResult();
        if (!state) return;
        if (state.status === "failed")
          return { type: "failed" as const, error: state.error.message };
        return state.result;
      },
    });
  }

  for (const plugin of context.plugins) {
    await handlePluginError(plugin, "initPublishPlan", () =>
      plugin.initPublishPlan?.call(context, { lock, plan }),
    );
  }

  return plan;
}

/** additional metadata of publish tasks, can be extended from other places */
export interface PublishTaskMetadata {}

export interface PublishTaskContext {
  context: TegamiContext;
  plan: PublishPlan;
}

export type PublishTaskRunContext = PublishTaskContext;

// merge the optional metadata fields into the class, safe since every member is optional
// oxlint-disable-next-line no-unused-vars, no-unsafe-declaration-merging
export interface PublishTask<T = unknown> extends PublishTaskMetadata {}

export abstract class PublishTask<T = unknown> {
  /** a short title for the task */
  abstract name: string;
  /** describe the purpose of the task */
  description?: string;
  /**
   * Tasks that must settle before this one runs, they must be part of the publish tasks,
   * and circular `wait` relationships are rejected with an error. Duplicated items are allowed.
   *
   * Failed tasks don't prevent this task from running, inspect them with `getResult`.
   */
  wait: PublishTask[] = [];
  /**
   * Like `wait`, but the waited tasks may not be part of the publish tasks (ignored),
   * and edges that close a dependency cycle are dropped to break the cycle.
   */
  optionalWait: PublishTask[] = [];

  /** @internal set when the task settles, always assigned by the task runner after `run` */
  $state?: PublishTaskState<T>;

  /** inspect the outcome of the task, `undefined` when the task has not settled */
  getResult(): PublishTaskState<T> | undefined {
    return this.$state;
  }

  abstract run(opts: PublishTaskRunContext): Awaitable<T>;

  /** link task-level dependencies, called after every task is created */
  link?(opts: PublishTaskContext): void;

  /**
   * Check if the task's effects are already applied (e.g. from a previous run), without running it.
   *
   * Used to resolve publish plan status, return nothing when the task has no opinion.
   */
  status?(opts: PublishTaskContext): Awaitable<"done" | "pending" | void | undefined>;
}

export type PublishTaskState<T = unknown> =
  | { status: "success"; result: T }
  | { status: "failed"; error: Error };

const startedTasks = new WeakSet<PublishTask>();

/**
 * Run tasks concurrently, respecting their `wait` & `optionalWait` relationships
 * (see {@link scheduleTasks} for how cycles are resolved).
 *
 * Failed tasks never prevent dependents from running, tasks can inspect the outcome of
 * their waited tasks with `getResult` and decide on their own.
 *
 * Errors thrown by tasks are captured into the task states, never thrown. Task instances
 * are single-use; publish hooks create a fresh graph for every run.
 * Scheduling takes O(tasks + dependency edges) time and space.
 */
export async function runPublishTasks(
  tasks: PublishTask[],
  {
    context,
    plan,
    concurrency = DEFAULT_CONCURRENCY,
  }: {
    context: TegamiContext;
    plan: PublishPlan;
    /** max amount of concurrently running tasks */
    concurrency?: number;
  },
): Promise<void> {
  assertConcurrency(concurrency);

  const schedule = scheduleTasks(tasks);
  for (const task of tasks) {
    if (startedTasks.has(task)) {
      throw new Error(
        `Publish task "${task.name}" has already been run; task instances are single-use.`,
      );
    }
    startedTasks.add(task);
  }

  const runContext: PublishTaskRunContext = { plan, context };

  async function run(task: PublishTask) {
    try {
      task.$state = { status: "success", result: await task.run(runContext) };
    } catch (e) {
      task.$state = {
        status: "failed",
        error: e instanceof Error ? e : new Error(String(e)),
      };
    }
  }

  let slots = concurrency;
  const waiters = new Set<() => void>();
  async function acquire() {
    if (slots > 0) {
      slots--;
    } else {
      await new Promise<void>((resolve) => waiters.add(resolve));
    }
  }
  function release() {
    const next = waiters.values().next().value;
    if (next) {
      waiters.delete(next);
      next();
    } else {
      slots++;
    }
  }

  const runs = new Map<PublishTask, Promise<void>>();
  for (const [task, deps] of schedule) {
    runs.set(
      task,
      Promise.all(Array.from(deps, (dep) => runs.get(dep)!)).then(async () => {
        await acquire();
        try {
          await run(task);
        } finally {
          release();
        }
      }),
    );
  }
  await Promise.all(runs.values());
}

/**
 * The returned map iterates in execution order (a topological order of the dependency
 * graph), each task mapped to the dependencies it waits for at run-time. Construction
 * takes O(tasks + dependency edges) time and space.
 */
function scheduleTasks(tasks: PublishTask[]): Map<PublishTask, Set<PublishTask>> {
  const taskSet = new Set(tasks);
  if (taskSet.size !== tasks.length) {
    throw new Error("The publish task list contains the same task instance more than once.");
  }
  const resolved = new Map<PublishTask, Set<PublishTask>>();
  const stack: PublishTask[] = [];
  const active = new Map<PublishTask, { index: number; hardEdges: number }>();
  let hardEdges = 0;

  /** returns `false` when the edge to this task must be dropped to break a cycle */
  function scan(task: PublishTask): boolean {
    const cycle = active.get(task);
    if (cycle) {
      if (hardEdges > cycle.hardEdges) {
        throw new Error(
          `circular reference of deps: ${[...stack.slice(cycle.index), task]
            .map((t) => t.name)
            .join(" -> ")}`,
        );
      }
      return false;
    }
    if (resolved.has(task)) return true;

    const deps = new Set<PublishTask>();
    active.set(task, { index: stack.length, hardEdges });
    stack.push(task);
    for (const dep of task.wait) {
      if (!taskSet.has(dep)) {
        throw new Error(
          `Task "${task.name}" waits on task "${dep.name}" which is not part of the publish tasks.`,
        );
      }
      hardEdges++;
      if (scan(dep)) deps.add(dep);
      hardEdges--;
    }

    for (const dep of task.optionalWait) {
      if (!taskSet.has(dep) || dep === task) continue;
      if (scan(dep)) deps.add(dep);
    }

    stack.pop();
    active.delete(task);
    resolved.set(task, deps);
    return true;
  }

  for (const task of tasks) scan(task);
  return resolved;
}

/**
 * Publishes a single package with the shared pipeline: dry-run handling,
 * `willPublish`/`afterPublish` hooks. Thrown failures are captured by the task runner.
 *
 * Providers extend this class and implement `publish()` (and optionally `status()`).
 */
export abstract class PackagePublishTask<
  T extends WorkspacePackage = WorkspacePackage,
> extends PublishTask<PackagePublishTaskResult> {
  name: string;

  constructor(readonly pkg: T) {
    super();
    this.name = `publish:${pkg.id}`;
  }

  /** provider-specific publishing; throw when publishing fails */
  abstract publish(opts: PublishTaskRunContext): Awaitable<PackagePublishTaskResult>;

  /** link publish tasks from preflight `wait`/`optionalWait` data */
  link({ plan }: PublishTaskContext): void {
    const preflight = plan.packages.get(this.pkg.id)?.preflight;
    if (!preflight) return;

    // unknown or unpublished dependencies are ignored
    for (const t of plan.tasks) {
      if (!(t instanceof PackagePublishTask) || t === this) continue;
      if (preflight.wait?.includes(t.pkg.id)) this.wait.push(t);
      if (preflight.optionalWait?.includes(t.pkg.id)) this.optionalWait.push(t);
    }
  }

  async run(opts: PublishTaskRunContext): Promise<PackagePublishTaskResult> {
    const { context, plan } = opts;
    const pkg = this.pkg;
    let result: PackagePublishTaskResult | undefined;

    try {
      if (plan.options.dryRun ?? false) {
        result = { type: "published" };
      } else {
        for (const plugin of context.plugins) {
          const next = await handlePluginError(plugin, "willPublish", () =>
            plugin.willPublish?.call(context, { pkg }),
          );

          if (next === false) {
            result = { type: "skipped" };
            break;
          }
        }

        result ??= await this.publish(opts);
      }

      this.$state = { status: "success", result };
      return result;
    } catch (e) {
      this.$state = {
        status: "failed",
        error: e instanceof Error ? e : new Error(String(e)),
      };
      throw e;
    } finally {
      if (!result || result.type !== "skipped") {
        for (const plugin of context.plugins) {
          await handlePluginError(plugin, "afterPublish", () =>
            plugin.afterPublish?.call(context, { pkg, plan }),
          );
        }
      }
    }
  }
}

/** backward compatibility: publishes a package through the legacy `publish` hook chain */
class LegacyPublishTask extends PackagePublishTask {
  async publish({ context, plan }: PublishTaskRunContext): Promise<PackagePublishTaskResult> {
    const { pkg } = this;

    for (const plugin of context.plugins) {
      const publishResult = await handlePluginError(plugin, "publish", () =>
        plugin.publish?.call(context, { pkg, plan }),
      );

      if (publishResult?.type === "failed") throw new Error(publishResult.error);
      if (publishResult) return publishResult;
    }

    throw new Error(
      `There is no plugin to publish package "${pkg.id}", please make sure the package has a supported provider plugin.`,
    );
  }
}

/** backward compatibility: runs a plugin's `afterPublishAll` hook as a task */
export class PluginAfterPublishAllTask extends PublishTask<void> {
  name: string;

  constructor(
    private readonly plugin: TegamiPlugin,
    previous?: PluginAfterPublishAllTask,
  ) {
    super();
    this.name = `${plugin.name}:after-publish-all`;
    if (previous) this.wait.push(previous);
  }

  /** legacy behaviour: `afterPublishAll` runs after every package publish, including tasks of plugins later in the plugin order */
  link({ plan }: PublishTaskContext): void {
    for (const t of plan.tasks) {
      if (t instanceof PackagePublishTask) this.wait.push(t);
    }
  }

  async run({ context, plan }: PublishTaskRunContext): Promise<void> {
    // legacy behaviour: a failed publish task aborts the `afterPublishAll` hooks
    for (const dep of this.wait) {
      if (dep.getResult()?.status === "failed") return;
    }

    await handlePluginError(this.plugin, "afterPublishAll", () =>
      this.plugin.afterPublishAll!.call(context, { plan }),
    );
  }
}

/** backward compatibility: reports a plugin's `resolvePlanStatus` hook as a task status */
class PluginPlanStatusTask extends PublishTask<void> {
  name: string;

  constructor(private readonly plugin: TegamiPlugin) {
    super();
    this.name = `${plugin.name}:plan-status`;
  }

  run() {}

  async status({ context, plan }: PublishTaskContext) {
    const status = await handlePluginError(this.plugin, "resolvePlanStatus", () =>
      this.plugin.resolvePlanStatus!.call(context, { plan }),
    );

    if (Array.isArray(status)) {
      if (await somePromise(status, (v) => v === "pending")) return "pending" as const;
      return;
    }

    if (status === "pending") return "pending" as const;
    if (status === "success") return "done" as const;
  }
}

export async function collectPublishTasks(
  context: TegamiContext,
  plan: PublishPlan,
): Promise<PublishTask[]> {
  const hookContext = { plan };
  const tasks: PublishTask[] = (plan.tasks = []);
  const packageTasks = new Set<string>();
  for (const plugin of context.plugins) {
    const created = await handlePluginError(plugin, "publishTasks", () =>
      plugin.publishTasks?.call(context, hookContext),
    );
    const createdTasks = Array.isArray(created) ? created : [created];
    for (const task of createdTasks) {
      if (!task) continue;

      if (task instanceof PackagePublishTask) {
        if (!plan.packages.get(task.pkg.id)?.preflight?.shouldPublish) {
          throw new Error(
            `Plugin "${plugin.name}" created package publish task "${task.name}" for "${task.pkg.id}", but that package is not selected for publishing.`,
          );
        }

        if (packageTasks.has(task.pkg.id)) {
          throw new Error(
            `Package "${task.pkg.id}" has multiple publish tasks. Only one PackagePublishTask is allowed per package.`,
          );
        }
        packageTasks.add(task.pkg.id);
        packagePublishTasks.set(plan.packages.get(task.pkg.id)!, task);
      }

      tasks.push(task);
    }
  }

  // backward compatibility: packages without a publish task go through the legacy `publish` hook chain
  for (const [id, packagePlan] of plan.packages) {
    if (!packagePlan.preflight?.shouldPublish) continue;
    if (packageTasks.has(id)) continue;
    const pkg = context.graph.get(id);
    if (pkg) {
      const task = new LegacyPublishTask(pkg);
      tasks.push(task);
      packagePublishTasks.set(packagePlan, task);
    }
  }

  let previousAfterPublishAll: PluginAfterPublishAllTask | undefined;
  for (const plugin of context.plugins) {
    if (plugin.afterPublishAll) {
      const task = new PluginAfterPublishAllTask(plugin, previousAfterPublishAll);
      tasks.push(task);
      previousAfterPublishAll = task;
    }
    if (plugin.resolvePlanStatus) {
      tasks.push(new PluginPlanStatusTask(plugin));
    }
  }

  for (const task of tasks) {
    task.link?.({ context, plan });
  }

  return tasks;
}

export interface PublishOptions {
  /** Validate the publish plan without publishing packages, creating tags, or running release plugins. */
  dryRun?: boolean;

  /**
   * Publish only the given packages and their dependencies.
   *
   * Each entry can be a package id, package name, or `group:name`.
   *
   * When empty, no packages will be published.
   */
  packages?: string[];

  /**
   * The max amount of concurrently running publish tasks & status checks (unstable, can change in anytime).
   *
   * @default 5
   */
  unstable_maxChunk?: number;
}

/** Successful outcome returned by a package publish task. Publish failures must be thrown. */
export type PackagePublishTaskResult = {
  type: "published" | "skipped";
};

/** Outcome exposed on a package's publish plan, including failures captured by the task runner. */
export type PackagePublishResult =
  | PackagePublishTaskResult
  | {
      type: "failed";
      error: string;
    };

export async function runPublishPlan(context: TegamiContext, plan: PublishPlan) {
  const { unstable_maxChunk = DEFAULT_CONCURRENCY } = plan.options;

  for (const plugin of context.plugins) {
    await handlePluginError(plugin, "beforePublishAll", () =>
      plugin.beforePublishAll?.call(context, { plan }),
    );
  }

  const tasks = await collectPublishTasks(context, plan);
  await runPublishTasks(tasks, { context, plan, concurrency: unstable_maxChunk });

  const errors = new Set<Error>();
  for (const task of tasks) {
    const state = task.getResult();
    if (state?.status === "failed") errors.add(state.error);
  }
  if (errors.size === 1) throw errors.values().next().value;
  if (errors.size > 1) {
    throw new AggregateError(errors, `${errors.size} publish tasks failed.`);
  }
}

export async function runPreflights(context: TegamiContext, plan: PublishPlan): Promise<void> {
  const { graph } = context;

  await Promise.all(
    Array.from(plan.packages, async ([id, packagePlan]) => {
      const pkg = graph.get(id)!;

      packagePlan.preflight = { shouldPublish: false };
      if (!packagePlan.updated) return;

      for (const plugin of context.plugins) {
        const res = await handlePluginError(plugin, "publishPreflight", () =>
          plugin.publishPreflight?.call(context, { pkg, plan }),
        );

        if (res) {
          packagePlan.preflight = res;
          break;
        }
      }
    }),
  );

  if (plan.options.packages) {
    const only = new Set<string>();
    function addOnly(id: string) {
      if (only.has(id)) return;
      const preflight = plan.packages.get(id)?.preflight;
      if (!preflight) return;

      only.add(id);
      if (preflight.wait) for (const dep of preflight.wait) addOnly(dep);
      if (preflight.optionalWait) for (const dep of preflight.optionalWait) addOnly(dep);
    }

    for (const name of plan.options.packages) {
      for (const pkg of graph.getByName(name)) addOnly(pkg.id);
    }

    for (const [id, packagePlan] of plan.packages) {
      if (only.has(id)) continue;
      packagePlan.preflight!.shouldPublish = false;
    }
  }

  for (const plugin of context.plugins) {
    await handlePluginError(plugin, "afterPreflight", () =>
      plugin.afterPreflight?.call(context, { plan }),
    );
  }
}

/**
 * Check the status of every task of the plan, running at most `unstable_maxChunk` checks
 * at a time. Checks that have not started yet are skipped once a task reports `pending`.
 */
export async function publishPlanStatus(
  plan: PublishPlan,
  context: TegamiContext,
): Promise<{
  status: "success" | "pending";
  reason?: string;
}> {
  const { unstable_maxChunk = DEFAULT_CONCURRENCY } = plan.options;
  assertConcurrency(unstable_maxChunk);
  const tasks = await collectPublishTasks(context, plan);

  let next = 0;
  let pending: PublishTask | undefined;
  async function check() {
    while (!pending && next < tasks.length) {
      const task = tasks[next++]!;
      if ((await task.status?.({ context, plan })) === "pending") pending = task;
    }
  }
  await Promise.all(Array.from({ length: Math.min(unstable_maxChunk, tasks.length) }, check));

  if (pending) {
    return { status: "pending", reason: `Task "${pending.name}" is pending` };
  }

  return { status: "success" };
}
